// Bundles every file in src/components/ui into src/generated/sources.ts so
// component pages can show their own source without reading the disk at runtime.
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const uiDir = path.join(root, "src", "components", "ui");
const outFile = path.join(root, "src", "generated", "sources.ts");

const files = (await readdir(uiDir)).filter((f) => f.endsWith(".tsx") || f.endsWith(".ts")).sort();
const entries = await Promise.all(
  files.map(async (file) => {
    const repoPath = `src/components/ui/${file}`;
    const code = await readFile(path.join(uiDir, file), "utf8");
    return `  ${JSON.stringify(repoPath)}: ${JSON.stringify(code.replace(/\r\n/g, "\n"))},`;
  }),
);

await mkdir(path.dirname(outFile), { recursive: true });
await writeFile(
  outFile,
  `// Generated by scripts/generate-sources.mjs. Do not edit.\nexport const sources: Record<string, string> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`Bundled ${files.length} component sources`);
